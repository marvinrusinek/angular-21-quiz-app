/**
 * Create this run's throwaway database, immediately before the backend starts.
 *
 * WHY THIS IS NOT IN globalSetup: Playwright launches `webServer` BEFORE
 * globalSetup, so a database created there does not exist yet when the backend
 * opens its pool — the server exits with `database "e2e_…" does not exist` and
 * the whole run fails before a single test. SQLite hid this ordering entirely,
 * because it creates its file on demand.
 *
 * Running as part of the webServer command makes the ordering a fact rather
 * than an assumption.
 *
 * Plain JavaScript on purpose: this runs via the shell in front of `npm run
 * dev`, with no transpiler in the chain.
 */
const { Client } = require('pg');

const NAME_PREFIX = 'e2e_';

const name = (process.env.E2E_DATABASE_NAME || '').trim();
const adminUrl = (process.env.E2E_ADMIN_DATABASE_URL || '').trim();

function fail(message) {
  console.error(`[e2e-db] ${message}`);
  process.exit(1);
}

if (!name) fail('E2E_DATABASE_NAME is not set');
if (!adminUrl) fail('E2E_ADMIN_DATABASE_URL is not set');

// The same guard the TypeScript harness applies: only ever create a database
// this harness generated.
if (!name.startsWith(NAME_PREFIX)) {
  fail(`refusing to create a database not named ${NAME_PREFIX}*: ${name}`);
}

(async () => {
  const client = new Client({
    connectionString: adminUrl,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 30_000
  });
  await client.connect();
  try {
    const { rows } = await client.query('SELECT 1 FROM pg_database WHERE datname = $1', [name]);
    if (rows.length === 0) {
      // Identifiers cannot be parameterized. The name is generated by the
      // harness and validated above, so it is never user input.
      await client.query(`CREATE DATABASE "${name}"`);
      console.log(`[e2e-db] created throwaway database ${name}`);
    } else {
      console.log(`[e2e-db] reusing throwaway database ${name}`);
    }
  } finally {
    await client.end();
  }
})().catch((err) => fail(`could not create ${name}: ${err.message}`));
